    def process(self, word: str, context: dict = None) -> Dict:
        """返回: {semantic_types: [(family, confidence), ...]}"""
        results = []

        for family, word_set in self.semantic_families.items():
            if word in word_set:
                results.append((family, 0.95))

        if not results:
            # 启发式猜测
            if word.endswith("人") or word.endswith("者") or word.endswith("员"):
                results.append(("人物", 0.50))
            elif word.endswith("品") or word.endswith("具"):
                results.append(("物体", 0.40))
            elif word.endswith("处") or word.endswith("室") or word.endswith("园"):
                results.append(("地点", 0.40))
            else:
                results.append(("未知", 0.10))

        return {"semantic_types": results}
